create extension if not exists btree_gist with schema extensions;

-- ------------------------------------------------------------ tabelas

create table if not exists public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  name        text not null check (char_length(name) between 1 and 80),
  username    text,
  avatar      text check (avatar is null or avatar ~ '^https?://'),
  bio         text not null default '' check (char_length(bio) <= 1000),
  is_admin    boolean not null default false,
  created_at  timestamptz not null default now()
);
create unique index if not exists profiles_username_key on public.profiles (lower(username));

create table if not exists public.listings (
  id               bigint generated by default as identity primary key,
  host_id          uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  title            text not null check (char_length(btrim(title)) between 1 and 100),
  description      text not null default '' check (char_length(description) <= 5000),
  property_type    text not null default 'Apartamento'
                   check (property_type in ('Casa','Apartamento','Chalé','Pousada','Quarto','Cabana','Sítio','Loft')),
  city             text not null check (char_length(btrim(city)) between 1 and 80),
  state            text not null default '' check (char_length(state) <= 80),
  country          text not null default 'Brasil' check (char_length(country) <= 80),
  lat              double precision check (lat between -90 and 90),
  lng              double precision check (lng between -180 and 180),
  price_per_night  numeric(10,2) not null check (price_per_night between 1 and 100000),
  cleaning_fee     numeric(10,2) not null default 0 check (cleaning_fee between 0 and 100000),
  max_guests       int not null default 1 check (max_guests between 1 and 50),
  bedrooms         int not null default 1 check (bedrooms between 0 and 50),
  beds             int not null default 1 check (beds between 1 and 100),
  bathrooms        numeric(4,1) not null default 1 check (bathrooms between 0 and 50),
  amenities        text[] not null default '{}',
  photos           text[] not null check (cardinality(photos) between 1 and 20),
  instant_book     boolean not null default false,
  active           boolean not null default true,
  created_at       timestamptz not null default now()
);
create index if not exists listings_host_idx on public.listings (host_id);

-- Endereço exato separado: só anfitrião, admin e hóspede com reserva confirmada veem.
create table if not exists public.listing_private (
  listing_id  bigint primary key references public.listings (id) on delete cascade,
  address     text not null default '' check (char_length(address) <= 200)
);

create table if not exists public.bookings (
  id               bigint generated by default as identity primary key,
  listing_id       bigint not null references public.listings (id) on delete cascade,
  guest_id         uuid not null references public.profiles (id) on delete cascade,
  check_in         date not null,
  check_out        date not null,
  guests           int not null check (guests between 1 and 50),
  nights           int not null check (nights between 1 and 90),
  price_per_night  numeric(10,2) not null,
  cleaning_fee     numeric(10,2) not null,
  total_price      numeric(12,2) not null,
  status           text not null default 'pending'
                   check (status in ('pending','confirmed','declined','cancelled')),
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  check (check_out > check_in)
);
-- Impede duas reservas ativas no mesmo imóvel com noites em comum.
do $$ begin
  alter table public.bookings add constraint bookings_no_overlap
    exclude using gist (listing_id with =, daterange(check_in, check_out) with &&)
    where (status in ('pending','confirmed'));
exception when duplicate_table or duplicate_object then null; end $$;
create index if not exists bookings_guest_idx on public.bookings (guest_id);

create table if not exists public.messages (
  id          bigint generated by default as identity primary key,
  booking_id  bigint not null references public.bookings (id) on delete cascade,
  sender_id   uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  body        text not null check (char_length(btrim(body)) between 1 and 2000),
  created_at  timestamptz not null default now()
);
create index if not exists messages_booking_idx on public.messages (booking_id);

create table if not exists public.reviews (
  id          bigint generated by default as identity primary key,
  booking_id  bigint not null unique references public.bookings (id) on delete cascade,
  listing_id  bigint not null references public.listings (id) on delete cascade,
  author_id   uuid not null references public.profiles (id) on delete cascade,
  rating      int not null check (rating between 1 and 5),
  comment     text not null default '' check (char_length(comment) <= 2000),
  created_at  timestamptz not null default now()
);
create index if not exists reviews_listing_idx on public.reviews (listing_id);

create table if not exists public.favorites (
  user_id     uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  listing_id  bigint not null references public.listings (id) on delete cascade,
  created_at  timestamptz not null default now(),
  primary key (user_id, listing_id)
);

-- ------------------------------------------------------------ funções auxiliares

-- "Hoje" no fuso do Brasil (o servidor do Supabase usa UTC).
create or replace function public.today_br() returns date
language sql stable set search_path = public as $$ select (now() at time zone 'America/Sao_Paulo')::date $$;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select is_admin from public.profiles where id = auth.uid()), false)
$$;

-- Cria o perfil automaticamente quando alguém se cadastra.
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, name)
  values (new.id, left(coalesce(nullif(btrim(new.raw_user_meta_data ->> 'name'), ''),
                                split_part(new.email, '@', 1)), 80))
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Login por nome de usuário (ex.: "jacson") -> e-mail da conta.
create or replace function public.login_email(p_login text) returns text
language sql stable security definer set search_path = public as $$
  select u.email::text from auth.users u join public.profiles p on p.id = u.id
  where p.username is not null and lower(p.username) = lower(btrim(p_login)) limit 1
$$;

-- ------------------------------------------------------------ RLS (quem vê / altera o quê)

alter table public.profiles        enable row level security;
alter table public.listings        enable row level security;
alter table public.listing_private enable row level security;
alter table public.bookings        enable row level security;
alter table public.messages        enable row level security;
alter table public.reviews         enable row level security;
alter table public.favorites       enable row level security;

-- Perfis: públicos para leitura; cada um edita só nome, bio e foto do próprio perfil.
drop policy if exists "profiles: leitura pública" on public.profiles;
create policy "profiles: leitura pública" on public.profiles for select using (true);
drop policy if exists "profiles: editar o próprio" on public.profiles;
create policy "profiles: editar o próprio" on public.profiles for update to authenticated
  using (id = auth.uid()) with check (id = auth.uid());
revoke insert, update, delete on public.profiles from anon, authenticated;
grant update (name, bio, avatar) on public.profiles to authenticated;

-- Anúncios: ativos são públicos; o anfitrião vê/edita os seus; admin vê todos.
drop policy if exists "listings: leitura" on public.listings;
create policy "listings: leitura" on public.listings for select
  using (active or host_id = auth.uid() or public.is_admin());
drop policy if exists "listings: criar" on public.listings;
create policy "listings: criar" on public.listings for insert to authenticated
  with check (host_id = auth.uid());
drop policy if exists "listings: editar" on public.listings;
create policy "listings: editar" on public.listings for update to authenticated
  using (host_id = auth.uid()) with check (host_id = auth.uid());
drop policy if exists "listings: excluir sem reservas" on public.listings;
create policy "listings: excluir sem reservas" on public.listings for delete to authenticated
  using (host_id = auth.uid()
         and not exists (select 1 from public.bookings b where b.listing_id = listings.id));

drop policy if exists "listing_private: leitura" on public.listing_private;
create policy "listing_private: leitura" on public.listing_private for select using (
  public.is_admin()
  or exists (select 1 from public.listings l where l.id = listing_id and l.host_id = auth.uid())
  or exists (select 1 from public.bookings b where b.listing_id = listing_private.listing_id
             and b.guest_id = auth.uid() and b.status = 'confirmed'));
drop policy if exists "listing_private: anfitrião grava" on public.listing_private;
create policy "listing_private: anfitrião grava" on public.listing_private for all to authenticated
  using (exists (select 1 from public.listings l where l.id = listing_id and l.host_id = auth.uid()))
  with check (exists (select 1 from public.listings l where l.id = listing_id and l.host_id = auth.uid()));

-- Reservas: hóspede, anfitrião do imóvel e admin leem. Criar/alterar só pelas funções abaixo.
drop policy if exists "bookings: participantes" on public.bookings;
create policy "bookings: participantes" on public.bookings for select using (
  guest_id = auth.uid()
  or exists (select 1 from public.listings l where l.id = listing_id and l.host_id = auth.uid())
  or public.is_admin());
revoke insert, update, delete on public.bookings from anon, authenticated;

-- Mensagens: quem pode ver a reserva lê e escreve (em seu próprio nome).
drop policy if exists "messages: leitura" on public.messages;
create policy "messages: leitura" on public.messages for select
  using (exists (select 1 from public.bookings b where b.id = booking_id));
drop policy if exists "messages: enviar" on public.messages;
create policy "messages: enviar" on public.messages for insert to authenticated
  with check (sender_id = auth.uid() and exists (select 1 from public.bookings b where b.id = booking_id));
revoke update, delete on public.messages from anon, authenticated;

-- Avaliações: públicas; criadas só pela função create_review.
drop policy if exists "reviews: leitura pública" on public.reviews;
create policy "reviews: leitura pública" on public.reviews for select using (true);
revoke insert, update, delete on public.reviews from anon, authenticated;

drop policy if exists "favorites: os meus" on public.favorites;
create policy "favorites: os meus" on public.favorites for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

-- ------------------------------------------------------------ views (respeitam o RLS de quem consulta)

create or replace view public.listing_cards with (security_invoker = on) as
select l.*, p.name as host_name, p.avatar as host_avatar,
       (select round(avg(r.rating), 2) from public.reviews r where r.listing_id = l.id) as rating,
       (select count(*) from public.reviews r where r.listing_id = l.id)::int as review_count
from public.listings l join public.profiles p on p.id = l.host_id;

create or replace view public.booking_details with (security_invoker = on) as
select b.*, l.title as listing_title, l.city as listing_city, l.state as listing_state,
       l.photos as listing_photos, l.host_id,
       g.name as guest_name, g.avatar as guest_avatar,
       h.name as host_name, h.avatar as host_avatar,
       exists (select 1 from public.reviews r where r.booking_id = b.id) as has_review,
       (select count(*) from public.messages m where m.booking_id = b.id)::int as message_count
from public.bookings b
join public.listings l on l.id = b.listing_id
join public.profiles g on g.id = b.guest_id
join public.profiles h on h.id = l.host_id;

-- ------------------------------------------------------------ regras de negócio (RPC)

-- Períodos ocupados de um anúncio (sem expor quem reservou).
create or replace function public.listing_unavailable(p_listing_id bigint)
returns table (check_in date, check_out date)
language sql stable security definer set search_path = public as $$
  select b.check_in, b.check_out from public.bookings b
  where b.listing_id = p_listing_id and b.status in ('pending','confirmed')
    and b.check_out >= public.today_br()
  order by b.check_in
$$;

-- Anúncios ocupados num período (para a busca por datas).
create or replace function public.booked_listing_ids(p_check_in date, p_check_out date)
returns setof bigint
language sql stable security definer set search_path = public as $$
  select distinct b.listing_id from public.bookings b
  where b.status in ('pending','confirmed') and b.check_in < p_check_out and b.check_out > p_check_in
$$;

create or replace function public.create_booking(
  p_listing_id bigint, p_check_in date, p_check_out date, p_guests int, p_message text default ''
) returns json
language plpgsql security definer set search_path = public as $$
declare
  l public.listings;
  v_nights int;
  v_status text;
  v_id bigint;
begin
  if auth.uid() is null then raise exception 'Faça login para continuar.'; end if;
  select * into l from public.listings where id = p_listing_id;
  if not found or not l.active then raise exception 'Anúncio não disponível.'; end if;
  if l.host_id = auth.uid() then raise exception 'Você não pode reservar o seu próprio anúncio.'; end if;
  if p_check_in is null or p_check_out is null then raise exception 'Escolha as datas de check-in e check-out.'; end if;
  if p_check_in < public.today_br() then raise exception 'O check-in não pode ser no passado.'; end if;
  v_nights := p_check_out - p_check_in;
  if v_nights < 1 then raise exception 'A estadia deve ter pelo menos 1 noite.'; end if;
  if v_nights > 90 then raise exception 'A estadia pode ter no máximo 90 noites.'; end if;
  if p_guests is null or p_guests < 1 or p_guests > l.max_guests then
    raise exception 'Este lugar aceita de 1 a % hóspedes.', l.max_guests;
  end if;
  v_status := case when l.instant_book then 'confirmed' else 'pending' end;
  begin
    insert into public.bookings (listing_id, guest_id, check_in, check_out, guests, nights,
                                 price_per_night, cleaning_fee, total_price, status)
    values (l.id, auth.uid(), p_check_in, p_check_out, p_guests, v_nights,
            l.price_per_night, l.cleaning_fee, v_nights * l.price_per_night + l.cleaning_fee, v_status)
    returning id into v_id;
  exception when exclusion_violation then
    raise exception 'Essas datas não estão mais disponíveis.';
  end;
  if coalesce(btrim(p_message), '') <> '' then
    insert into public.messages (booking_id, sender_id, body)
    values (v_id, auth.uid(), left(btrim(p_message), 2000));
  end if;
  return json_build_object('id', v_id, 'status', v_status);
end $$;

-- confirm / decline: anfitrião ou admin, pedido pendente e futuro.
-- cancel: hóspede, anfitrião ou admin, antes do check-in.
create or replace function public.booking_action(p_booking_id bigint, p_action text)
returns void
language plpgsql security definer set search_path = public as $$
declare
  b record;
  v_role text;
begin
  select bk.id, bk.guest_id, bk.status, bk.check_in, l.host_id into b
  from public.bookings bk join public.listings l on l.id = bk.listing_id where bk.id = p_booking_id;
  if not found then raise exception 'Reserva não encontrada.'; end if;
  if auth.uid() = b.host_id then v_role := 'host';
  elsif auth.uid() = b.guest_id then v_role := 'guest';
  elsif public.is_admin() then v_role := 'admin';
  else raise exception 'Reserva não encontrada.';
  end if;

  if p_action in ('confirm', 'decline') then
    if v_role = 'guest' or b.status <> 'pending' or b.check_in < public.today_br() then
      raise exception 'Esta reserva não pode ser %.',
        case p_action when 'confirm' then 'confirmada' else 'recusada' end;
    end if;
    update public.bookings
       set status = case p_action when 'confirm' then 'confirmed' else 'declined' end, updated_at = now()
     where id = p_booking_id;
  elsif p_action = 'cancel' then
    if b.status not in ('pending', 'confirmed') or b.check_in <= public.today_br() then
      raise exception 'Esta reserva não pode mais ser cancelada.';
    end if;
    update public.bookings set status = 'cancelled', updated_at = now() where id = p_booking_id;
  else
    raise exception 'Ação inválida.';
  end if;
end $$;

-- Avaliação: só o hóspede, estadia confirmada e concluída, uma vez.
create or replace function public.create_review(p_booking_id bigint, p_rating int, p_comment text default '')
returns void
language plpgsql security definer set search_path = public as $$
declare b public.bookings;
begin
  select * into b from public.bookings where id = p_booking_id;
  if not found or b.guest_id is distinct from auth.uid() or b.status <> 'confirmed'
     or b.check_out > public.today_br()
     or exists (select 1 from public.reviews r where r.booking_id = p_booking_id) then
    raise exception 'Você só pode avaliar estadias concluídas, uma vez.';
  end if;
  if p_rating is null or p_rating not between 1 and 5 then raise exception 'Escolha uma nota de 1 a 5.'; end if;
  insert into public.reviews (booking_id, listing_id, author_id, rating, comment)
  values (b.id, b.listing_id, b.guest_id, p_rating, left(coalesce(btrim(p_comment), ''), 2000));
end $$;

-- E-mails dos usuários (somente admin).
create or replace function public.admin_users()
returns table (id uuid, email text)
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Acesso restrito ao administrador.'; end if;
  return query select u.id, u.email::text from auth.users u;
end $$;

